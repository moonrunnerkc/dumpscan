// Embeds fixtures/versions/<ecosystem>/corpus.json into packages/versions so the
// comparator ruleset digest can be computed without touching the filesystem.
// Run with --check to fail when the checked-in modules have drifted.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname;
const fixtures = join(root, 'fixtures/versions');
const target = join(root, 'packages/versions/src/corpus');

const HEADER = `// Generated by scripts/generate-corpus-module.mjs from fixtures/versions.
// Edit the fixture and regenerate; do not edit this file.
`;

function quote(value) {
  return JSON.stringify(value);
}

function renderList(values, indent) {
  if (values.length === 0) return '[]';
  const pad = ' '.repeat(indent + 2);
  return `[\n${values.map((v) => `${pad}${quote(v)},`).join('\n')}\n${' '.repeat(indent)}]`;
}

function renderPairs(pairs, indent) {
  if (pairs.length === 0) return '[]';
  const pad = ' '.repeat(indent + 2);
  return `[\n${pairs.map(([a, b]) => `${pad}[${quote(a)}, ${quote(b)}],`).join('\n')}\n${' '.repeat(indent)}]`;
}

function renderModule(slug, corpus) {
  const name = slug.replace(/[^a-z0-9]/g, '_').toUpperCase();
  return `${HEADER}
import type { VersionCorpus } from '../corpus-types.js';

export const ${name}_CORPUS: VersionCorpus = {
  ecosystem: ${quote(corpus.ecosystem)},
  comparator: ${quote(corpus.comparator)},
  reference: ${quote(corpus.reference)},
  ordered: ${renderList(corpus.ordered, 2)},
  equal: ${renderPairs(corpus.equal, 2)},
  invalid: ${renderList(corpus.invalid, 2)},
};
`;
}

function renderIndex(slugs) {
  const imports = slugs
    .map((slug) => {
      const name = slug.replace(/[^a-z0-9]/g, '_').toUpperCase();
      return `import { ${name}_CORPUS } from './${slug}.js';`;
    })
    .join('\n');
  const list = slugs
    .map((slug) => `  ${slug.replace(/[^a-z0-9]/g, '_').toUpperCase()}_CORPUS,`)
    .join('\n');
  return `${HEADER}
import type { VersionCorpus } from '../corpus-types.js';
${imports}

/** Every comparator corpus, ordered by ecosystem so the digest is stable. */
export const ALL_CORPORA: readonly VersionCorpus[] = [
${list}
];
`;
}

function build() {
  const slugs = readdirSync(fixtures).sort();
  const files = new Map();
  for (const slug of slugs) {
    const corpus = JSON.parse(readFileSync(join(fixtures, slug, 'corpus.json'), 'utf8'));
    files.set(join(target, `${slug}.ts`), renderModule(slug, corpus));
  }
  files.set(join(target, 'all.ts'), renderIndex(slugs));
  return files;
}

const files = build();

if (process.argv.includes('--check')) {
  const drifted = [];
  for (const [path, text] of files) {
    let actual = '';
    try {
      actual = readFileSync(path, 'utf8');
    } catch {
      actual = '';
    }
    if (actual !== text) drifted.push(path.slice(root.length));
  }
  if (drifted.length > 0) {
    console.error('Comparator corpus modules are out of date:');
    for (const path of drifted) console.error(`  ${path}`);
    console.error(
      '\nRun pnpm gen:corpus. Regenerating changes comparatorRulesetDigest, so say so in the commit message.',
    );
    process.exit(1);
  }
  console.log(`corpus modules current (${files.size} files)`);
} else {
  mkdirSync(target, { recursive: true });
  for (const [path, text] of files) writeFileSync(path, text);
  console.log(`wrote ${files.size} corpus modules`);
}
